"""H13-I proof attempt (session 9): test candidate structural approaches
before trying to prove `I(pi) <= floor((n-1)^2/4)` for all pi (PLAN §8,
docs/notes/h13_line_model.md §6).

Definitions match experiments/line_model.py / line_profile.c exactly:
  double cut (r0, c0) in Z_n x Z_n: w_j = (pi[(r0+j) % n] - c0) % n, j=0..n-1;
  I(pi) = min_{r0,c0} inv(w).  (r0 = q+1, c0 = q+1-c in the line_model.py
  parametrisation; ranging (q,c) over Z_n x Z_n is the same as ranging
  (r0,c0) over Z_n x Z_n, so this is the same I(pi) as C33/C35/C36.)

Sub-experiments (each --only flag runs one; default runs all for the given
n-range, which should stay small — see AGENTS.md rule 9):

1. --pairsum: verify (as a sanity check on the "quadrant" reformulation
   suggested by the task) that
     sum_{r0,c0} inv(pi; r0,c0) = sum_{pairs {i,k}} [n*d + n*e - 2*d*e]
   where d = (k-i) % n, e = (pi[k]-pi[i]) % n (the pair's row/column cyclic
   gaps).  This is the identity behind the "point in one-named quadrant of a
   pair" picture: discordant-count(d,e) = n*d + n*e - 2*d*e, so the pair's
   *concordant* measure over the n^2 origins is n^2/2 - (n*d+n*e-2*d*e) =
   (n-d)*(n-e) + d*e.  Confirms the identity; does not by itself bound the
   MINIMUM (only the average, which is known not to work: see notes §6 and
   part 2 below).

2. --recurrence: verify the row/column shift-by-one recurrences
     inv(r0+1, c0) - inv(r0, c0) = n - 1 - 2*x,   x = (pi[r0] - c0) % n
     inv(r0, c0+1) - inv(r0, c0) = n - 1 - 2*p,   p = (pi^{-1}[c0] - r0) % n
   ("joint/simultaneous shift" candidate (a) of PLAN §8 / notes §6: these
   are the two elementary steps a joint-shift argument would compose).

3. --compress: candidate "reflections are the unique local maximum of I
   under elementary moves on pi itself" (a compression/rearrangement
   argument, distinct from the already-rejected "shift the cut" Lemma C).
   Two move sets: adjacent position-swap (swap pi(i), pi(i+1)) and adjacent
   value-swap (swap the positions of values v, v+1).  Reports, for each n,
   how many pi are local maxima of I under each move set, and how many of
   those are NOT reflections.

4. --diagonal: candidate "n canonical origins suffice" — restrict c0 to
   c0 = pi[r0] (head starts exactly at a data point, so the front element of
   the line has value 0).  Reports on how many pi this n-origin restriction
   already fails to reach floor((n-1)^2/4) (i.e. is a strictly weaker
   family than the full n^2 origins).

5. --affine: for the affine family pi(i) = a*i + b (mod n), gcd(a, n) = 1,
   I(pi) does not depend on b (both r0 and c0 absorb additive shifts), so
   only a matters.  This is a *structured family*, not full enumeration, so
   it may be run at n beyond the exhaustive ladder (AGENTS.md rule 9).
   Reports max_a I(pi_a) and the maximizing a.

6. --circtransp: cross-check against the literature lead found by web
   search (van Zuylen, Bieron, Schalekamp, Yu, "A tight upper bound on the
   number of cyclically adjacent transpositions to sort a permutation",
   IPL 2016 / arXiv:1402.4867 abstract; Even-Zohar, "The Writhe of
   Permutations and Random Framed Knots", RSA 2017 / arXiv:1511.09469
   abstract — primary sources were NOT reachable, arxiv.org and
   onlinelibrary.wiley.com are blocked by this sandbox's egress policy, so
   neither definition could be read in full).  Computes, by a single BFS
   from the identity, the diameter of the Cayley graph generated by the
   n adjacent transpositions {i,i+1 mod n} (i.e. sorting distance allowing
   ALSO the wrap-around transposition (n-1,0)), and compares it PER
   PERMUTATION against I(pi) (double cut) and the single-cut analogue
   I_single(pi) = min_{r0} inv(rotate positions only, no value shift).  This
   checks whether that distance coincides with either of our quantities
   before any claim from that literature is used.

Usage: python3 experiments/h13i_attempt.py --nmax 8
Output: data/runs/h13i_attempt/report.json, report.md.
Version h13i_attempt-1.0.
"""

import argparse
import itertools
import json
import os
import sys
import time
from collections import deque

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.join(ROOT, "oracle"))
from moves import CORE_VERSION  # noqa: E402

VERSION = "h13i_attempt-1.0"
OUT = os.path.join(ROOT, "data", "runs", "h13i_attempt")


def inversions(w):
    n = len(w)
    return sum(1 for i in range(n) for j in range(i + 1, n) if w[i] > w[j])


def I_double(pi):
    n = len(pi)
    best = None
    for r0 in range(n):
        for c0 in range(n):
            w = [(pi[(r0 + j) % n] - c0) % n for j in range(n)]
            inv = inversions(w)
            if best is None or inv < best:
                best = inv
    return best


def I_single(pi):
    n = len(pi)
    best = None
    for r0 in range(n):
        w = [pi[(r0 + j) % n] for j in range(n)]
        inv = inversions(w)
        if best is None or inv < best:
            best = inv
    return best


def I_diagonal(pi):
    n = len(pi)
    return min(inversions([(pi[(r0 + j) % n] - pi[r0]) % n for j in range(n)]) for r0 in range(n))


def pairsum_check(nmin, nmax, log):
    for n in range(nmin, nmax + 1):
        for name, pi in family_examples(n, seed=n).items():
            grid_sum = sum(
                inversions([(pi[(r0 + j) % n] - c0) % n for j in range(n)])
                for r0 in range(n) for c0 in range(n)
            )
            formula_sum = 0
            for i in range(n):
                for k in range(i + 1, n):
                    d = (k - i) % n
                    e = (pi[k] - pi[i]) % n
                    formula_sum += n * d + n * e - 2 * d * e
            ok = grid_sum == formula_sum
            log(f"  pairsum n={n} {name}: grid_sum={grid_sum} formula_sum={formula_sum} {'OK' if ok else 'MISMATCH'}")
            if not ok:
                raise AssertionError("pairsum identity failed")


def family_examples(n, seed=0):
    import random
    ident = tuple(range(n))
    sigma = tuple((1 - i) % n for i in range(n))
    rev = tuple(range(n - 1, -1, -1))
    rnd = list(range(n))
    random.Random(seed).shuffle(rnd)
    return {"id": ident, "sigma": sigma, "rev": rev, "rnd": tuple(rnd)}


def recurrence_check(nmin, nmax, log, trials=6):
    import random
    for n in range(nmin, nmax + 1):
        bad = 0
        for t in range(trials):
            pi = list(range(n))
            random.Random(1000 * n + t).shuffle(pi)
            inv_inv = [0] * n
            for i, v in enumerate(pi):
                inv_inv[v] = i
            for r0 in range(n):
                for c0 in range(n):
                    w0 = inversions([(pi[(r0 + j) % n] - c0) % n for j in range(n)])
                    w_r = inversions([(pi[(r0 + 1 + j) % n] - c0) % n for j in range(n)])
                    w_c = inversions([(pi[(r0 + j) % n] - (c0 + 1) % n) % n for j in range(n)])
                    x = (pi[r0] - c0) % n
                    p = (inv_inv[c0] - r0) % n
                    if w_r - w0 != n - 1 - 2 * x:
                        bad += 1
                    if w_c - w0 != n - 1 - 2 * p:
                        bad += 1
        log(f"  recurrence n={n}: {trials} random pi, all (r0,c0) checked, mismatches={bad}")
        if bad:
            raise AssertionError("recurrence check failed")


def pos_swap_neighbors(pi):
    n = len(pi)
    for i in range(n):
        j = (i + 1) % n
        pi2 = list(pi)
        pi2[i], pi2[j] = pi2[j], pi2[i]
        yield tuple(pi2)


def val_swap_neighbors(pi):
    n = len(pi)
    inv = [0] * n
    for i, v in enumerate(pi):
        inv[v] = i
    for v in range(n):
        v2 = (v + 1) % n
        i1, i2 = inv[v], inv[v2]
        pi2 = list(pi)
        pi2[i1], pi2[i2] = v2, v
        yield tuple(pi2)


def compress_check(nmin, nmax, log):
    rows = []
    for n in range(nmin, nmax + 1):
        t0 = time.time()
        refl = set(tuple((h - i) % n for i in range(n)) for h in range(n))
        Ivals = {}
        for pi in itertools.permutations(range(n)):
            Ivals[pi] = I_double(pi)
        lmax_pos = [pi for pi in Ivals if all(Ivals[q] <= Ivals[pi] for q in pos_swap_neighbors(pi))]
        lmax_val = [pi for pi in Ivals if all(Ivals[q] <= Ivals[pi] for q in val_swap_neighbors(pi))]
        extra_pos = [pi for pi in lmax_pos if pi not in refl]
        extra_val = [pi for pi in lmax_val if pi not in refl]
        row = {"n": n, "count": len(Ivals), "local_maxima_pos": len(lmax_pos),
               "local_maxima_val": len(lmax_val), "non_reflection_local_maxima_pos": len(extra_pos),
               "non_reflection_local_maxima_val": len(extra_val),
               "example_non_reflection_pos": list(extra_pos[0]) if extra_pos else None,
               "seconds": round(time.time() - t0, 1)}
        rows.append(row)
        log(f"  compress n={n}: local maxima pos-swap={len(lmax_pos)} (non-reflection {len(extra_pos)}), "
            f"val-swap={len(lmax_val)} (non-reflection {len(extra_val)}); {row['seconds']} s")
    return rows


def diagonal_check(nmin, nmax, log):
    rows = []
    for n in range(nmin, nmax + 1):
        t0 = time.time()
        bound = (n - 1) ** 2 // 4
        fails = 0
        worst = 0
        worst_pi = None
        for pi in itertools.permutations(range(n)):
            d = I_diagonal(pi)
            if d > bound:
                fails += 1
                if d > worst:
                    worst, worst_pi = d, pi
        row = {"n": n, "bound": bound, "count": factorial(n), "diagonal_exceeds_bound": fails,
               "worst_diagonal": worst, "worst_pi": list(worst_pi) if worst_pi else None,
               "seconds": round(time.time() - t0, 1)}
        rows.append(row)
        log(f"  diagonal n={n}: bound={bound}, n-origin restriction exceeds bound on {fails}/{row['count']} pi "
            f"(worst {worst} at {worst_pi}); {row['seconds']} s")
    return rows


def factorial(n):
    r = 1
    for k in range(2, n + 1):
        r *= k
    return r


def affine_check(nmin, nmax, log):
    import math
    rows = []
    for n in range(nmin, nmax + 1):
        bound = (n - 1) ** 2 // 4
        worst, worst_a = -1, None
        for a in range(1, n):
            if math.gcd(a, n) != 1:
                continue
            pi = tuple((a * i) % n for i in range(n))
            I = I_double(pi)
            if I > worst:
                worst, worst_a = I, a
        rows.append({"n": n, "bound": bound, "max_over_affine": worst, "argmax_a": worst_a})
        log(f"  affine n={n}: bound={bound}, max_a I(pi_a)={worst} at a={worst_a} "
            f"(a=n-1 is the reflection pi(i)=-i, already covered by C32/C33)")
    return rows


def circtransp_bfs_from_identity(n):
    """Single BFS from identity over the whole S_n Cayley graph generated by
    the n adjacent transpositions {i,i+1 mod n} (includes the wrap-around
    (n-1,0)); returns dist[pi] for all pi (as tuples)."""
    target = tuple(range(n))
    dist = {target: 0}
    dq = deque([target])
    while dq:
        cur = dq.popleft()
        d = dist[cur]
        for i in range(n):
            j = (i + 1) % n
            nxt = list(cur)
            nxt[i], nxt[j] = nxt[j], nxt[i]
            nxt = tuple(nxt)
            if nxt not in dist:
                dist[nxt] = d + 1
                dq.append(nxt)
    return dist


def circtransp_check(nmin, nmax, log):
    rows = []
    for n in range(nmin, nmax + 1):
        t0 = time.time()
        dist = circtransp_bfs_from_identity(n)
        maxD = max(dist.values())
        mism_single = mism_double = 0
        for pi in itertools.permutations(range(n)):
            D = dist[pi]
            if D != I_single(pi):
                mism_single += 1
            if D != I_double(pi):
                mism_double += 1
        n2_4 = n * n // 4
        row = {"n": n, "max_dist": maxD, "n_squared_over_4": n2_4,
               "mismatches_vs_I_single": mism_single, "mismatches_vs_I_double": mism_double,
               "count": factorial(n), "seconds": round(time.time() - t0, 1)}
        rows.append(row)
        log(f"  circtransp n={n}: max sorting distance (adjacent + wrap transpositions) = {maxD} "
            f"(floor(n^2/4) = {n2_4}); mismatches vs I_single={mism_single}, vs I_double={mism_double} "
            f"out of {row['count']}; {row['seconds']} s")
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nmin", type=int, default=4)
    ap.add_argument("--nmax", type=int, default=7)
    ap.add_argument("--affine-nmax", type=int, default=12)
    ap.add_argument("--only", choices=["pairsum", "recurrence", "compress", "diagonal", "affine", "circtransp"],
                    default=None)
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    logf = open(os.path.join(OUT, "report.log"), "a")

    def log(msg):
        print(msg, flush=True)
        logf.write(msg + "\n")
        logf.flush()

    log(f"== {VERSION} {CORE_VERSION} args={vars(args)}")
    t0 = time.time()
    report = {"version": VERSION, "core": CORE_VERSION, "args": vars(args)}

    todo = [args.only] if args.only else ["pairsum", "recurrence", "compress", "diagonal", "affine", "circtransp"]

    if "pairsum" in todo:
        log("-- 1. pairsum identity (quadrant reformulation sanity check) --")
        pairsum_check(args.nmin, args.nmax, log)
        report["pairsum"] = "OK (identity verified on id/sigma/rev/random, 4<=n<={})".format(args.nmax)
    if "recurrence" in todo:
        log("-- 2. row/column shift-by-one recurrence --")
        recurrence_check(args.nmin, args.nmax, log)
        report["recurrence"] = "OK (verified on random pi, all (r0,c0), 4<=n<={})".format(args.nmax)
    if "compress" in todo:
        log("-- 3. compression / local-maxima under adjacent swaps --")
        report["compress"] = compress_check(args.nmin, args.nmax, log)
    if "diagonal" in todo:
        log("-- 4. n canonical ('diagonal') origins are not enough --")
        report["diagonal"] = diagonal_check(args.nmin, args.nmax, log)
    if "affine" in todo:
        log("-- 5. affine family pi(i) = a*i mod n --")
        report["affine"] = affine_check(args.nmin, args.affine_nmax, log)
    if "circtransp" in todo:
        log("-- 6. cyclically-adjacent-transposition sorting distance cross-check --")
        report["circtransp"] = circtransp_check(args.nmin, args.nmax, log)

    report["seconds"] = round(time.time() - t0, 1)
    with open(os.path.join(OUT, "report.json"), "w") as f:
        json.dump(report, f, indent=1)
    log(f"== done in {report['seconds']} s")


if __name__ == "__main__":
    main()
