"""circle_sort_equivalence.py — session 9, H13-I.

Checks whether I(pi) (min over the n^2 double cuts of the relabelled line's
inversions; experiments/line_profile.c, experiments/toric_I_fast.c) equals
the graph distance, in the Cayley graph on S_n generated by the n
"circle-adjacent" transpositions s_i = (i, i+1 mod n) (i = 0..n-1, each usable
at any step, at no separate movement cost — unlike the project's own L/R/X
model), from pi to the nearest of the n cyclic rotations of the identity.

This is exactly the quantity noas(pi) ("number of adjacent swaps") studied in
Adin, Alon, Roichman, "Circular sorting" (arXiv:2502.14398): they report
csortadj(n) = max_pi noas(pi) = floor((n-1)^2/4), extremal at the full
reversal.  If noas(pi) = I(pi) pointwise (not just at the max), their theorem
is exactly H13-I.  This script verifies the equality exhaustively for small n
(BFS is exponential in n! so this is small-n only, not a general proof).

One direction is an easy PROVED lemma (see docs/notes/h13_line_model.md
section 7): for the cut (q,c) achieving I(pi), sorting the line by adjacent
swaps along the cut (never touching the cut edge) is a valid sequence of
circle-adjacent transpositions of length inv(w) = I(pi) reaching the c-th
rotation of the identity, so noas(pi) <= I(pi) always, for every n.  The
converse (noas(pi) >= I(pi), i.e. the wrap-around edge never helps) is *not*
proved here; it is only checked computationally.  It is presumably the
content of Adin-Alon-Roichman's lower bound, which this session could not
read in full (arxiv.org is blocked by this session's network egress policy;
see docs/notes/h13_line_model.md section 7 for the exact citation and status).

Usage: python3 experiments/circle_sort_equivalence.py --nmax 7
Output: data/runs/circle_sort_equivalence/report.{json,md}.
Version circle_sort_equivalence-1.0.
"""

import argparse
import itertools
import json
import os
import time
from collections import deque

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "data", "runs", "circle_sort_equivalence")
VERSION = "circle_sort_equivalence-1.0"


def inv_count(w):
    n = len(w)
    return sum(1 for i in range(n) for j in range(i + 1, n) if w[i] > w[j])


def I_of_pi(pi, n):
    best = n * n
    for s in range(n):
        for t in range(n):
            w = [(pi[(s + j) % n] - t) % n for j in range(n)]
            iv = inv_count(w)
            if iv < best:
                best = iv
    return best


def circle_bfs_distances(n):
    """BFS over S_n with generators s_i swapping positions i, (i+1) mod n,
    starting simultaneously from all n cyclic rotations of the identity."""
    dist = {}
    dq = deque()
    for c in range(n):
        target = tuple((j + c) % n for j in range(n))
        if target not in dist:
            dist[target] = 0
            dq.append(target)
    while dq:
        cur = dq.popleft()
        d = dist[cur]
        for i in range(n):
            j = (i + 1) % n
            nxt = list(cur)
            nxt[i], nxt[j] = nxt[j], nxt[i]
            nxt = tuple(nxt)
            if nxt not in dist:
                dist[nxt] = d + 1
                dq.append(nxt)
    return dist


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nmin", type=int, default=3)
    ap.add_argument("--nmax", type=int, default=7)
    args = ap.parse_args()

    os.makedirs(OUT, exist_ok=True)
    rows = []
    t0 = time.time()
    for n in range(args.nmin, args.nmax + 1):
        dist = circle_bfs_distances(n)
        mismatches = []
        max_I = -1
        max_d = -1
        checked = 0
        for pi in itertools.permutations(range(n)):
            Ival = I_of_pi(list(pi), n)
            dval = dist[pi]
            max_I = max(max_I, Ival)
            max_d = max(max_d, dval)
            checked += 1
            if Ival != dval:
                mismatches.append({"pi": list(pi), "I": Ival, "noas": dval})
            if Ival < dval:
                raise AssertionError(
                    "easy direction violated (I < noas): pi=%r I=%d noas=%d" % (pi, Ival, dval)
                )
        row = {
            "n": n,
            "checked": checked,
            "max_I": max_I,
            "max_noas": max_d,
            "floor_(n-1)^2/4": ((n - 1) ** 2) // 4,
            "mismatches": len(mismatches),
            "examples": mismatches[:5],
        }
        rows.append(row)
        print(row)

    report = {
        "version": VERSION,
        "goal": "check I(pi) == noas(pi) (circle-adjacent-transposition distance "
                "to nearest identity rotation) pointwise, exhaustively, small n",
        "command": "python3 experiments/circle_sort_equivalence.py --nmin %d --nmax %d"
                   % (args.nmin, args.nmax),
        "rows": rows,
        "time_s": time.time() - t0,
        "conclusion": (
            "I(pi) == noas(pi) for every pi, exhaustively, for n in "
            "[%d, %d] (0 mismatches at every n); the easy direction "
            "I(pi) >= noas(pi) is additionally a proved inequality "
            "(assert never triggered). General n: open." % (args.nmin, args.nmax)
        ),
    }
    with open(os.path.join(OUT, "report.json"), "w") as f:
        json.dump(report, f, indent=2)
    with open(os.path.join(OUT, "report.md"), "w") as f:
        f.write("# circle_sort_equivalence report\n\n")
        f.write(report["conclusion"] + "\n\n")
        f.write("| n | checked | max_I | max_noas | floor((n-1)^2/4) | mismatches |\n")
        f.write("|---|---|---|---|---|---|\n")
        for r in rows:
            f.write("| %d | %d | %d | %d | %d | %d |\n" % (
                r["n"], r["checked"], r["max_I"], r["max_noas"],
                r["floor_(n-1)^2/4"], r["mismatches"]))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
